-- Дали проверката е минала през двигател с живо търсене.
--
-- Без този признак двата различни въпроса се събират в едно число: „в
-- отговора ли си днес“ (двигател, който търси в момента на въпроса) и „знае
-- ли изобщо за теб“ (модел, който отговаря от паметта си). Средното между тях
-- не значи нито едното, нито другото.
--
-- Подразбиращата се стойност е 0. Записите отпреди тази миграция са правени с
-- модели БЕЗ търсене — така че 0 е верният им отговор, не удобният.
ALTER TABLE visibility_checks ADD COLUMN grounded INTEGER NOT NULL DEFAULT 0;

CREATE INDEX IF NOT EXISTS visibility_grounded
  ON visibility_checks (domain_id, grounded, created_utc DESC);
